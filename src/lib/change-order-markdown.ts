import type { AnalysisResult } from "./types";
import type { SideHustleInsights } from "./side-hustle-types";

export function formatChangeOrderMarkdown(
  result: AnalysisResult,
  hourlyRate: number,
  insights: SideHustleInsights,
  clientName = "Client",
): string {
  const lines: string[] = [
    `# Change Order — ${result.changeOrder?.title ?? "Additional scope"}`,
    ``,
    `**Prepared for:** ${clientName}  `,
    `**Date:** ${new Date().toLocaleDateString("en-US", { dateStyle: "medium" })}  `,
    `**Valid for sign-off:** 5 business days`,
    ``,
    `## Summary`,
    result.summary,
    ``,
  ];

  if (result.changeOrder) {
    lines.push(
      `## Line items`,
      ``,
      `| Description | Hours | Rate | Subtotal |`,
      `| --- | ---: | ---: | ---: |`,
    );
    let subtotal = 0;
    for (const li of result.changeOrder.lineItems) {
      const sub = li.hours * hourlyRate;
      subtotal += sub;
      lines.push(
        `| ${li.description} | ${li.hours} | $${hourlyRate} | $${sub} |`,
      );
    }
    if (insights.rushFeePercent > 0) {
      const rush = Math.round(subtotal * (insights.rushFeePercent / 100));
      lines.push(`| Rush fee (${insights.rushFeePercent}%) | — | — | $${rush} |`);
      subtotal += rush;
    }
    lines.push(``, `**Total:** $${subtotal} USD`, ``);
  }

  lines.push(
    `## Scope note`,
    `Work below is outside the signed SOW. Timeline and delivery dates for the original MVP are unchanged until this change order is approved in writing.`,
    ``,
    `## Sign-off`,
    `Approved by _________________________ Date _________`,
    ``,
    `---`,
    `_Generated by ScopeLock — open-weight AI for freelancers who bill for scope, not guilt._`,
  );

  return lines.join("\n");
}
